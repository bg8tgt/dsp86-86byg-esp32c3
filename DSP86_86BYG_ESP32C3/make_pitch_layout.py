def dash(p0,p1,c=BLK,w=2,n=18):
    for i in range(n):
        if i%2: continue
        a=i/n; b=(i+1)/n
        d.line([(p0[0]+(p1[0]-p0[0])*a,p0[1]+(p1[1]-p0[1])*a),
                (p0[0]+(p1[0]-p0[0])*b,p0[1]+(p1[1]-p0[1])*b)],fill=c,width=w)

